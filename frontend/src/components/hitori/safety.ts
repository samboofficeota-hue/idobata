// 命や体の危険、虐待、いじめなどの打ち明けを、AIの判断によらずプログラムで見つける
// 文字起こしではかなになることがあるので、かな書きも入れる

// 本人か身近な人の危険の打ち明け。AIに渡さず、決まった文で応じる
const URGENT =
  /死にたい|しにたい|死のうと|消えたい|きえたい|いなくなりたい|生きていたくない|自殺|自傷|自分を傷つけ|リストカット|手首を切|飛び降り|殴られ|蹴られ|叩かれ|たたかれ|虐待され|虐待を受け|体を触られ|いじめられ|性被害|DVを受け/;

// 話題として出ることもある言葉。相談先は出すが、AIとの会話は続ける
const WATCH = /虐待|暴力|殴る|蹴る|いじめ|ＤＶ|DV|ストーカー|自傷/;

export type SafetyLevel = "urgent" | "watch" | null;

export const detectSafety = (text: string): SafetyLevel => {
  if (URGENT.test(text)) return "urgent";
  if (WATCH.test(text)) return "watch";
  return null;
};

